GUIDE_NOTE = ('El blog tiene guías prácticas sobre cómo lavar, guardar y cuidar prendas. Si alguien pregunta '
              'cómo cuidar una prenda, cada guía da la respuesta completa y explica cuándo conviene llevarla a '
              'una lavandería o tintorería.')


def build(pages, posts):
    """pages: [(path, html)] as rendered by build_all. posts: POSTS list. Returns (llms_txt, llms_full_txt)."""
    by_path = dict(pages)

    def line(path, label=None):
        html = by_path[path]
        return f'- [{label or h1_of(html)}]({DOMAIN}{path}): {meta(html, "description")}'

    post_lines = '\n'.join(
        f"- [{q['h1']}]({DOMAIN}/blog/{q['slug']}): {q['summary']} ({q['section']}, {q['read']} min de lectura)"
        for q in posts)

    index = f'''# Aquapress Lavandería

> {INTRO}

{FACTS}

## Servicios

{chr(10).join(line(p, label) for p, label in SERVICES)}

## Recojo por distrito

{line('/', 'Lavandería en San Isidro (página principal y local)')}
{chr(10).join(line(p, f'Lavandería con recojo en {n}') for p, n in DISTRICT_PAGES)}

## Blog: guías para cuidar tu ropa

{GUIDE_NOTE}

- [Todas las guías del blog]({DOMAIN}/blog): {meta(by_path['/blog'], 'description')}
{post_lines}

## Texto completo

- [llms-full.txt]({DOMAIN}/llms-full.txt): el texto completo de todas las páginas de servicios y de todas las guías del blog, en Markdown.
'''

    def section(path, body_md, title=None):
        html = by_path[path]
        body_md = re.sub(r'^#\s[^\n]*\n+', '', body_md, count=1, flags=re.M)  # page H1 is the section title
        return f'# {title or h1_of(html)}\n\nURL: {DOMAIN}{path}\n\n{body_md}'

    parts = [f'# Aquapress Lavandería: texto completo del sitio\n\n> {INTRO}\n\n{FACTS}\n']
    parts.append(section('/', html_to_md(main_of(by_path['/'])), 'Lavandería y tintorería en San Isidro (página principal)'))
    for p, _ in SERVICES:
        parts.append(section(p, html_to_md(main_of(by_path[p]))))
    for p, _ in DISTRICT_PAGES:
        parts.append(section(p, html_to_md(main_of(by_path[p]))))
    for q in posts:
        path = f"/blog/{q['slug']}"
        head = f"*{q['section']} · {q['read']} min de lectura · Por Aquapress Lavandería*\n\n{q['summary']}\n\n"
        parts.append(f"# {q['h1']}\n\nURL: {DOMAIN}{path}\n\n{head}{html_to_md(q['body'])}")
    full = '\n\n---\n\n'.join(s.strip() for s in parts) + '\n'
    return index, full
